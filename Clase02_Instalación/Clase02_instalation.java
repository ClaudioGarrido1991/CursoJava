    /*
     *Instalación. 
     * 
     * Para programar en Java es necesario instalar
     * IDE: Entorno de desarrollo de Software.
     * JRE: Java Runtime Environment (Entorno de ejecución de Java.)
     * 
     * ¿Porque se necesita JRE?
     * 
     * Esto es debido a que la principal ventaja de Java es ser multiplataforma. Es decir que
     * cualquier maquina que soporte JRE podría compilar e interpretar el programa Java.
     * 
     * ¿Cómo lo hace?
     * 
     * Para crear un programa Java se crea el código fuente, al compilar se crea un Bytecode
     * que es un fichero intermedio con el código máquina.
     * 
     * Bytecode es un archivo .class
     * 
     * La desventaja de esto es que necesariamente requiere que esté instalada la JRE.
     * 
     * La ventaja es que el programa Java se crea una sola vez y debería correr en cualquier
     * maquina con JRE instalado.
     * 
     * "Write once, run everywhere". (Escribelo una vez, correlo en cualquier lado)
     * 
     * ¿Que es compilar?
     * 
     * El humano programa en un lenguaje mas comprensible para el (lenguaje alto nivel)
     * a esto se le llama código fuente, para que la maquina pueda entender estas instrucciones
     * es necesario que un compilador "traduzca" el código fuente a código maquina que es el
     * que la maquina entiende.
     * 
     * 
     */


    
